"""
Парсинг и семантическое сравнение версий

Версии в фидах неоднородны по длине: "15", "15.4.1", "2.41.0.2".
Сравнение «как строк» даст неверный порядок ("1.10" < "1.9"),
поэтому парсим версию в кортеж целых и сравниваем поэлементно,
дополняя нулями до одинаковой длины.

Никаких эвристик про "слипшиеся" компоненты не применяется:
версии трактуются как чисто числовые. Это осознанное решение -
см. README, раздел "Известные ограничения".

Диапазон уязвимости трактуется как полуоткрытый [start, fix): если
start <= version < fix то версия уязвима.
"""


def _split_parts(version: str) -> list[str]:
    """
    Разбить строку версии на компоненты и проверить их формат. Компоненты
    это только ASCII-цифры
    Args:
        version: строка версии, например "3.0.11" или "  2.41.0.2  "
    Returns:
        Список строковых компонентов, например ["3", "0", "11"],
        ведущие нули сохраняются
    """
    parts = version.strip().split('.')
    for p in parts:
        if not p or not p.isascii() or not p.isdigit():
            raise ValueError(f"Некорректная версия: {version!r}")
    return parts


def parse_version(version: str) -> tuple[int, ...]:
    """
    Разобрать строку версии в кортеж целых компонентов
    Args:
        version: строка версии, например "3.0.11" или "2.41.0.2".
    Returns:
        Кортеж целых компонентов, например (3, 0, 11)
    """
    return tuple(int(p) for p in _split_parts(version))


def cmp_version(a: str, b: str) -> int:
    """
    Сравнить две версии семантически. Обе версии разбираются в кортежи целых,
    дополняются нулями до одинаковой длины и сравниваются поэлементно.
    Благодаря паддингу "1.0" и "1.0.0" считаются равными
    Args:
        a: первая версия, например "3.0.11"
        b: вторая версия, например "3.0.9"
    Returns:
        -1, если a < b;
         0, если a == b;
         1, если a > b
    """
    va = parse_version(a)
    vb = parse_version(b)
    n = max(len(va), len(vb))
    va = va + (0,) * (n - len(va))
    vb = vb + (0,) * (n - len(vb))
    return (va > vb) - (va < vb)


def is_vulnerable(version: str, start_vuln_version: str,
                  fixed_version: str) -> bool:
    """
    Проверить, попадает ли версия в диапазон уязвимости [start, fix)
    Диапазон полуоткрытый:
      - version < start         не уязвима;
      - version == start        уязвима;
      - start < version < fix   уязвима;
      - version == fix          НЕ уязвима;
      - version > fix           не уязвима
    Args:
        version: проверяемая версия, например "15.3.1"
        start_vuln_version: нижняя граница диапазона (включительно, в фиде
            может быть неполной: "15" означает "15.x.x…")
        fixed_version: верхняя граница (исключительно), первая исправленная
            версия, например "15.4.1"
    Returns:
        True, если версия уязвима, иначе False
    """
    return (
        cmp_version(version, start_vuln_version) >= 0
        and cmp_version(version, fixed_version) < 0
    )
